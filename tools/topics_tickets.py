"""Adds a topic to every ticket question: by the PDD section of the first point referenced in the answer comment,
else by referenced signs or markings, else by keywords of the question."""
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
data = json.load(open(src, encoding='utf-8'))
by_section = {
    **{s: 'Общие положения и обязанности' for s in ('1', '2', '3', '4', '5')},
    '6': 'Сигналы светофора и регулировщика', '7': 'Аварийная сигнализация и знак аварийной остановки',
    '8': 'Начало движения, маневрирование', '9': 'Расположение на проезжей части', '10': 'Скорость движения',
    '11': 'Обгон, опережение, встречный разъезд', '12': 'Остановка и стоянка', '13': 'Проезд перекрёстков',
    '14': 'Пешеходные переходы и остановки', '15': 'Железнодорожные переезды', '16': 'Автомагистрали и жилые зоны', '17': 'Автомагистрали и жилые зоны',
    '18': 'Проезд перекрёстков', '19': 'Световые приборы и звуковой сигнал', '20': 'Буксировка, учебная езда, перевозки', '21': 'Буксировка, учебная езда, перевозки',
    '22': 'Буксировка, учебная езда, перевозки', '23': 'Буксировка, учебная езда, перевозки', '24': 'Мотоциклы, мопеды, велосипеды', '25': 'Буксировка, учебная езда, перевозки',
}
keywords = [
    ('Первая помощь', r'помощ|пострадавш|кровотеч|перелом|реанимац|сердечно|травм|ожог|обморок'),
    ('Ответственность водителя', r'штраф|лишени|ответственност|административн|уголовн|страхов'),
    ('Техническое состояние', r'неисправност|эксплуатац|шин[аыу]|протектор|тормозн(ая|ой) систем|рулев(ое|ого) управлени'),
    ('Железнодорожные переезды', r'переезд'),
    ('Буксировка, учебная езда, перевозки', r'буксир|перевоз|груз|учебн'),
    ('Сигналы светофора и регулировщика', r'светофор|регулировщик|сигнал(а|ы)? (светофора|регулировщика)'),
    ('Пешеходные переходы и остановки', r'пешеход'),
    ('Обгон, опережение, встречный разъезд', r'обгон|опережени|встречн(ый|ым) разъезд'),
    ('Остановка и стоянка', r'остановк|стоянк|останов(иться|ить)'),
    ('Проезд перекрёстков', r'перекр[её]ст|уступить дорогу|уступите дорогу|проедет'),
    ('Начало движения, маневрирование', r'поворот|разворот|перестро|траектори|задним ходом|полос'),
    ('Скорость движения', r'скорост|км/ч'),
    ('Дорожная разметка', r'разметк|линии'),
    ('Дорожные знаки', r'знак|табличк'),
]
counts = {}
for q in data['questions']:
    topic = None
    if q['points']:
        topic = by_section.get(q['points'][0].split('.')[0])
    if not topic and q['signs']: topic = 'Дорожные знаки'
    if not topic and q['marks']: topic = 'Дорожная разметка'
    if not topic:
        for name, pattern in keywords:
            if re.search(pattern, q['question'], re.I): topic = name; break
    q['topic'] = topic or 'Безопасность движения и техника управления'
    q['image'] = q['image'].replace('.jpg', '.webp') if q['image'] else None
    counts[q['topic']] = counts.get(q['topic'], 0) + 1
json.dump(data, open(dst, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
for k, v in sorted(counts.items(), key=lambda x: -x[1]): print(v, k)
